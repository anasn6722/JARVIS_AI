class RuntimeMemory:

    def __init__(self):

        self.last_app = None
        self.last_website = None
        self.last_search = None
        self.last_file = None
        self.last_tasks = None

    def clear(self):

        self.last_app = None
        self.last_website = None
        self.last_search = None
        self.last_file = None
        self.last_tasks = None